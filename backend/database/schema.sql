/* ============================================================================
   Freely — Microsoft SQL Server database schema
   ----------------------------------------------------------------------------
   Source of truth : docs/freely.dbml (project freely, database_type 'SQL Server')
   Target          : Microsoft SQL Server 2019+ / Azure SQL
   Conventions     :
     - All timestamps are datetime2 in UTC, default SYSUTCDATETIME().
     - Enum-like values are NVARCHAR + CHECK constraints.
     - Secure public identifiers (public_post_id, public_job_id,
       tracking_number) are generated by the application.
     - Files live in protected object storage; only metadata/storage keys here.
     - Append-only tables: *_status_history, audit_logs, job_receipts, post_views.

   HOW TO RUN (on an EMPTY database):
     sqlcmd -S <server> -U <user> -P <password> -Q "CREATE DATABASE freely"
     sqlcmd -S <server> -U <user> -P <password> -d freely -i database/schema.sql
   ============================================================================ */

SET XACT_ABORT ON;
SET NOCOUNT ON;

BEGIN TRANSACTION;

/* ============================================================================
   1. USERS, ORGANIZATIONS, DEPARTMENTS, MEMBERSHIPS AND ACCESS CONTROL
   ============================================================================ */

CREATE TABLE users (
    id                  bigint IDENTITY(1,1)  NOT NULL,
    user_handle         nvarchar(50)          NOT NULL,
    full_name           nvarchar(150)         NOT NULL,
    email               nvarchar(255)         NULL,
    phone               nvarchar(20)          NULL,
    password_hash       nvarchar(255)         NULL,
    bio                 nvarchar(500)         NULL,
    avatar_storage_key  nvarchar(500)         NULL,
    cover_storage_key   nvarchar(500)         NULL,
    website_url         nvarchar(500)         NULL,
    preferred_language  nvarchar(20)          NULL,
    is_verified         bit                   NOT NULL CONSTRAINT DF_users_is_verified DEFAULT (0),
    is_active           bit                   NOT NULL CONSTRAINT DF_users_is_active DEFAULT (1),
    created_at          datetime2             NOT NULL CONSTRAINT DF_users_created_at DEFAULT (SYSUTCDATETIME()),
    updated_at          datetime2             NULL,
    CONSTRAINT PK_users PRIMARY KEY (id),
    CONSTRAINT UQ_users_user_handle UNIQUE (user_handle)
);

-- Filtered unique indexes allow multiple NULLs (email/phone are optional).
CREATE UNIQUE INDEX UX_users_email ON users (email) WHERE email IS NOT NULL;
CREATE UNIQUE INDEX UX_users_phone ON users (phone) WHERE phone IS NOT NULL;

CREATE TABLE organizations (
    id                   bigint IDENTITY(1,1) NOT NULL,
    name                 nvarchar(200)        NOT NULL,
    slug                 nvarchar(220)        NOT NULL,
    organization_type    nvarchar(40)         NOT NULL,
    description          nvarchar(max)        NULL,
    website_url          nvarchar(500)        NULL,
    logo_storage_key     nvarchar(500)        NULL,
    contact_email        nvarchar(255)        NULL,
    contact_phone        nvarchar(20)         NULL,
    address              nvarchar(max)        NULL,
    city                 nvarchar(100)        NULL,
    state                nvarchar(100)        NULL,
    country              nvarchar(100)        NULL,
    created_by_user_id   bigint               NOT NULL,
    verification_status  nvarchar(20)         NOT NULL CONSTRAINT DF_organizations_verification DEFAULT ('unverified'),
    is_active            bit                  NOT NULL CONSTRAINT DF_organizations_is_active DEFAULT (1),
    created_at           datetime2            NOT NULL CONSTRAINT DF_organizations_created_at DEFAULT (SYSUTCDATETIME()),
    updated_at           datetime2            NULL,
    CONSTRAINT PK_organizations PRIMARY KEY (id),
    CONSTRAINT UQ_organizations_slug UNIQUE (slug),
    CONSTRAINT FK_organizations_created_by FOREIGN KEY (created_by_user_id) REFERENCES users (id),
    CONSTRAINT CK_organizations_type CHECK (organization_type IN
        ('school', 'university', 'private_organization', 'government_organization', 'ngo', 'other')),
    CONSTRAINT CK_organizations_verification CHECK (verification_status IN
        ('unverified', 'pending', 'verified', 'rejected'))
);

CREATE INDEX IX_organizations_type ON organizations (organization_type);
CREATE INDEX IX_organizations_created_by ON organizations (created_by_user_id);
CREATE INDEX IX_organizations_verification ON organizations (verification_status);
CREATE INDEX IX_organizations_is_active ON organizations (is_active);

