CREATE TABLE grievance_categories (
    id                     bigint IDENTITY(1,1) NOT NULL,
    parent_category_id     bigint               NULL,
    name                   nvarchar(120)        NOT NULL,
    code                   nvarchar(40)         NOT NULL,
    description            nvarchar(max)        NULL,
    default_department_id  bigint               NULL,
    is_active              bit                  NOT NULL CONSTRAINT DF_grievance_categories_active DEFAULT (1),
    CONSTRAINT PK_grievance_categories PRIMARY KEY (id),
    CONSTRAINT UQ_grievance_categories_code UNIQUE (code),
    CONSTRAINT FK_grievance_categories_parent FOREIGN KEY (parent_category_id) REFERENCES grievance_categories (id),
    CONSTRAINT FK_grievance_categories_dept FOREIGN KEY (default_department_id) REFERENCES departments (id)
);

CREATE TABLE grievances (
    id               bigint IDENTITY(1,1) NOT NULL,
    tracking_number  nvarchar(40)         NOT NULL,
    user_id          bigint               NOT NULL,
    category_id      bigint               NOT NULL,
    title            nvarchar(250)        NOT NULL,
    description      nvarchar(max)        NOT NULL,
    location_text    nvarchar(max)        NULL,
    address          nvarchar(max)        NULL,
    district         nvarchar(100)        NULL,
    state            nvarchar(100)        NULL,
    postal_code      nvarchar(15)         NULL,
    latitude         decimal(10,7)        NULL,
    longitude        decimal(10,7)        NULL,
    status           nvarchar(40)         NOT NULL CONSTRAINT DF_grievances_status DEFAULT ('submitted'),
    priority         nvarchar(20)         NOT NULL CONSTRAINT DF_grievances_priority DEFAULT ('medium'),
    is_anonymous     bit                  NOT NULL CONSTRAINT DF_grievances_is_anonymous DEFAULT (0),
    submitted_at     datetime2            NOT NULL CONSTRAINT DF_grievances_submitted DEFAULT (SYSUTCDATETIME()),
    acknowledged_at  datetime2            NULL,
    resolved_at      datetime2            NULL,
    closed_at        datetime2            NULL,
    reopened_at      datetime2            NULL,
    created_at       datetime2            NOT NULL CONSTRAINT DF_grievances_created DEFAULT (SYSUTCDATETIME()),
    updated_at       datetime2            NULL,
    CONSTRAINT PK_grievances PRIMARY KEY (id),
    CONSTRAINT UQ_grievances_tracking UNIQUE (tracking_number),
    CONSTRAINT FK_grievances_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT FK_grievances_category FOREIGN KEY (category_id) REFERENCES grievance_categories (id),
    CONSTRAINT CK_grievances_status CHECK (status IN
        ('submitted', 'acknowledged', 'under_review', 'assigned', 'in_progress',
         'awaiting_citizen', 'resolved', 'closed', 'rejected', 'reopened')),
    CONSTRAINT CK_grievances_priority CHECK (priority IN ('low', 'medium', 'high', 'critical'))
);

CREATE INDEX IX_grievances_user ON grievances (user_id);
CREATE INDEX IX_grievances_category ON grievances (category_id);
CREATE INDEX IX_grievances_status ON grievances (status);
CREATE INDEX IX_grievances_priority ON grievances (priority);
CREATE INDEX IX_grievances_submitted ON grievances (submitted_at);
CREATE INDEX IX_grievances_status_priority ON grievances (status, priority);

CREATE TABLE grievance_attachments (
    id                   bigint IDENTITY(1,1) NOT NULL,
