CREATE TABLE posts (
    id                 bigint IDENTITY(1,1) NOT NULL,
    author_user_id     bigint               NULL,  -- NULL for guest posts
    public_post_id     nvarchar(40)         NOT NULL,
    is_anonymous       bit                  NOT NULL CONSTRAINT DF_posts_is_anonymous DEFAULT (0),
    body               nvarchar(max)        NOT NULL,
    post_type          nvarchar(20)         NOT NULL CONSTRAINT DF_posts_post_type DEFAULT ('post'),
    visibility         nvarchar(20)         NOT NULL CONSTRAINT DF_posts_visibility DEFAULT ('public'),
    reply_to_post_id   bigint               NULL,
    quote_post_id      bigint               NULL,
    is_sensitive       bit                  NOT NULL CONSTRAINT DF_posts_is_sensitive DEFAULT (0),
    is_pinned          bit                  NOT NULL CONSTRAINT DF_posts_is_pinned DEFAULT (0),
    moderation_status  nvarchar(20)         NOT NULL CONSTRAINT DF_posts_moderation DEFAULT ('visible'),
    created_at         datetime2            NOT NULL CONSTRAINT DF_posts_created DEFAULT (SYSUTCDATETIME()),
    updated_at         datetime2            NULL,
    deleted_at         datetime2            NULL,
    CONSTRAINT PK_posts PRIMARY KEY (id),
    CONSTRAINT UQ_posts_public_id UNIQUE (public_post_id),
    CONSTRAINT FK_posts_author FOREIGN KEY (author_user_id) REFERENCES users (id),
    CONSTRAINT FK_posts_reply_to FOREIGN KEY (reply_to_post_id) REFERENCES posts (id),
    CONSTRAINT FK_posts_quote FOREIGN KEY (quote_post_id) REFERENCES posts (id),
    CONSTRAINT CK_posts_post_type CHECK (post_type IN ('post', 'reply', 'quote')),
    CONSTRAINT CK_posts_visibility CHECK (visibility IN ('public', 'followers', 'department', 'private')),
    CONSTRAINT CK_posts_moderation CHECK (moderation_status IN ('visible', 'hidden', 'removed', 'under_review'))
);

CREATE INDEX IX_posts_author ON posts (author_user_id);
CREATE INDEX IX_posts_created ON posts (created_at);
CREATE INDEX IX_posts_visibility_created ON posts (visibility, created_at);
CREATE INDEX IX_posts_reply_to ON posts (reply_to_post_id);
CREATE INDEX IX_posts_quote ON posts (quote_post_id);
CREATE INDEX IX_posts_moderation ON posts (moderation_status);

